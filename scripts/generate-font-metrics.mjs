import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import * as fontkit from "fontkit";

const FONT_ROOT = "node_modules/@excalidraw/excalidraw/dist/prod/fonts";
const families = {
  1: "Excalifont",
  2: "Nunito",
  3: "Cascadia",
};
const codePoints = Array.from({ length: 95 }, (_, index) => index + 32);

function sourceFont(directory) {
  for (const filename of readdirSync(join(FONT_ROOT, directory)).sort()) {
    if (!filename.endsWith(".woff2")) continue;
    const font = fontkit.openSync(join(FONT_ROOT, directory, filename));
    if (codePoints.every((codePoint) => font.hasGlyphForCodePoint(codePoint))) return font;
  }
  throw new Error(`No complete printable-ASCII font found for ${directory}`);
}

const metrics = Object.fromEntries(Object.entries(families).map(([id, directory]) => {
  const font = sourceFont(directory);
  const advances = Object.fromEntries(codePoints.map((codePoint) => {
    const glyph = String.fromCodePoint(codePoint);
    return [glyph, Number((font.glyphForCodePoint(codePoint).advanceWidth / font.unitsPerEm).toFixed(6))];
  }));
  return [id, advances];
}));

const output = `// Generated by scripts/generate-font-metrics.mjs.\nexport const FONT_ADVANCES = ${JSON.stringify(metrics, null, 2)};\n`;
writeFileSync("src/font-metrics.generated.js", output, "utf8");
